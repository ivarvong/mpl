"""Generate the typed data tables in src/core/data/ from matplotlib 3.11.x.

  markers.ts  marker paths in marker units, as matplotlib's MarkerStyle builds them
  colors.ts   named colors (BASE + CSS4 + TABLEAU)
  stylelib.ts bundled .mplstyle sheets, verbatim

Run: python3 tools/gen_tables.py
"""
import glob, json, math, os
import numpy as np
import matplotlib
import matplotlib.colors as mc
import matplotlib.font_manager as fm
from matplotlib.markers import MarkerStyle
from fontTools.ttLib import TTFont

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "core", "data")
os.makedirs(OUT, exist_ok=True)
HDR = f"// Generated by tools/gen_tables.py from matplotlib {matplotlib.__version__}. Do not edit.\n"

def write(name, body):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(HDR + body)

# (fonts: see tools/gen_fonts.py)

# ---- markers
names = ['o', 's', '^', 'v', '<', '>', 'D', 'd', 'x', '+', '*', '.', 'p', 'h', 'X', 'P']
CODE = {1: "M", 2: "L", 3: "Q", 4: "C", 79: "Z"}
marks = {}
for m in names:
    ms = MarkerStyle(m)
    p = ms.get_transform().transform_path(ms.get_path())
    v = np.round(p.vertices, 6).tolist()
    codes = p.codes.tolist() if p.codes is not None else [1] + [2] * (len(v) - 1)
    segs, i = [], 0
    while i < len(v):
        c = CODE[codes[i]]
        if c in ("M", "L"):
            segs.append([c, *v[i]]); i += 1
        elif c == "Q":
            segs.append(["Q", *v[i], *v[i + 1]]); i += 2
        elif c == "C":
            segs.append(["C", *v[i], *v[i + 1], *v[i + 2]]); i += 3
        else:
            segs.append(["Z"]); i += 1
    snap = ms.get_snap_threshold()
    marks[m] = dict(segs=segs, filled=bool(ms.is_filled()),
                    snapPx=(snap if snap is not None and math.isfinite(snap) else "Infinity"),
                    join=str(ms.get_joinstyle()), cap={"butt": "butt", "round": "round", "projecting": "square"}[str(ms.get_capstyle())])
body = json.dumps(marks).replace('"Infinity"', "Infinity")
write("markers.ts", f"""import type {{ Cap, Join, MarkerName, Seg }} from '../types.ts';
/** Marker outline in marker units (y up; scale by markersize px). Vertices snap to integers when size >= snapPx. */
export type MarkerDef = {{ readonly segs: readonly Seg[]; readonly filled: boolean; readonly snapPx: number; readonly join: Join; readonly cap: Cap }};
export const MARKERS: Readonly<Record<MarkerName, MarkerDef>> = {body};
export const MARKER_NAMES: readonly MarkerName[] = {json.dumps(names)};
""")

# ---- named colors
cols = sorted({k: mc.to_hex(v) for k, v in {**mc.BASE_COLORS, **mc.CSS4_COLORS, **mc.TABLEAU_COLORS}.items()}.items())
write("colors.ts", f"export const NAMED: ReadonlyMap<string, string> = new Map({json.dumps(cols)});\n")

# ---- style library
sd = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "stylelib")
styles = sorted((os.path.basename(f)[:-9], open(f).read()) for f in glob.glob(os.path.join(sd, "*.mplstyle")) if not os.path.basename(f).startswith("_"))
write("stylelib.ts", f"export const STYLELIB: ReadonlyMap<string, string> = new Map({json.dumps(styles, indent=0)});\n")
print(f"wrote {len(marks)} markers, {len(cols)} colors, {len(styles)} styles")
