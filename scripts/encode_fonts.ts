// Encode baked faces (the FaceData JSON that scripts/gen_fonts.py writes) into the compact modules
// src/fonts/<name>.ts, and check each one decodes back to exactly the same JSON.
//   node scripts/encode_fonts.ts <dir with <name>.json>   (scripts/gen_fonts.py runs it on build/fonts)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { decodeFace, FACE_CATALOG, VLQ_ALPHABET, type BakedFace, type CatalogEntry } from '../src/core/fontcodec.ts';
import type { FaceData } from '../src/core/fonts.ts';

const vlq = (xs: readonly number[]): string => {
  let s = '';
  for (const n of xs) {
    if (!Number.isInteger(n)) throw new Error(`not an integer: ${n}`);
    let v = n < 0 ? -2 * n + 1 : 2 * n;
    do { let d = v % 32; v = Math.floor(v / 32); if (v > 0) d += 32; s += VLQ_ALPHABET[d]; } while (v > 0);
  }
  return s;
};
const byGid = <T>(rec: Readonly<Record<string, T>>): [number, T][] => Object.entries(rec).map(([k, v]): [number, T] => [Number(k), v]).toSorted((a, b) => a[0] - b[0]);

export function encodeFace(d: FaceData, entry: CatalogEntry): BakedFace {
  if (d.family !== entry.family || d.weight !== entry.weight) throw new Error(`${entry.module}: baked as ${d.family} ${d.weight}`);
  const cmap: number[] = []; let cp = 0;
  for (const [ch, g] of Object.entries(d.cmap)) {
    const cps = [...ch];
    if (cps.length !== 1) throw new Error(`cmap key ${JSON.stringify(ch)} is not one code point`);
    const c = ch.codePointAt(0) || 0; cmap.push(c - cp, g); cp = c;
  }
  const cover: number[] = []; let last = 0;
  for (const [a, b] of d.cover) { cover.push(a - last, b - a); last = b; }
  const glyphs: number[] = []; let pg = 0;
  for (const [g, [adv, x0, x1, y0, y1]] of byGid(d.glyphs)) { glyphs.push(g - pg, adv, x0, x1 - x0, y0, y1 - y0); pg = g; }
  const outlines: number[] = []; pg = 0;
  for (const [g, contours] of byGid(d.outlines)) {
    outlines.push(g - pg, contours.length); pg = g;
    let x = 0, y = 0;
    for (const c of contours) {
      if (c.length % 3 !== 0) throw new Error(`gid ${g}: contour length ${c.length}`);
      outlines.push(c.length / 3);
      for (let i = 0; i < c.length; i += 3) {
        const tag = c[i + 2];
        if (tag !== 0 && tag !== 1 && tag !== 2) throw new Error(`gid ${g}: tag ${tag}`);
        outlines.push(3 * (c[i] - x) + tag, c[i + 1] - y); x = c[i]; y = c[i + 1];
      }
    }
  }
  const offsets: number[] = []; pg = 0;
  for (const [g, contours] of byGid(d.offsets)) { offsets.push(g - pg, contours.length); pg = g; for (const c of contours) offsets.push(c.length, ...c); }
  const kern: number[] = []; let pl = 0;
  for (const [k, v] of Object.entries(d.kern)) { const [l, r] = k.split(',').map(Number); kern.push(l - pl, r, v); pl = l; }
  return { id: entry.id, upm: d.upm, typo: d.typo, cmap: vlq(cmap), cover: vlq(cover), glyphs: vlq(glyphs), outlines: vlq(outlines), offsets: vlq(offsets), kern: vlq(kern), gsub: d.gsub };
}

const s = (v: unknown): string => JSON.stringify(v);
export function moduleSource(b: BakedFace, entry: CatalogEntry, source: string): string {
  return `// Generated by scripts/encode_fonts.ts from ${source} (scripts/gen_fonts.py). Do not edit.
// ${entry.family}, weight ${entry.weight}. Pass it to registerFonts() to render text in this face.
import type { BakedFace } from '../core/fontcodec.ts';
export const ${entry.binding}: BakedFace = {
  id: ${s(b.id)}, upm: ${b.upm}, typo: ${s(b.typo)},
  cmap: ${s(b.cmap)},
  cover: ${s(b.cover)},
  glyphs: ${s(b.glyphs)},
  outlines: ${s(b.outlines)},
  offsets: ${s(b.offsets)},
  kern: ${s(b.kern)},
  gsub: ${s(b.gsub)},
};
`;
}

if (import.meta.main) {
  const dir = process.argv[2] || '';
  if (dir === '') { console.error('usage: node scripts/encode_fonts.ts <dir of baked .json>'); process.exit(2); }
  const out = new URL('../src/fonts/', import.meta.url).pathname;
  for (const entry of FACE_CATALOG) {
    if (!existsSync(join(dir, `${entry.module}.json`))) { console.log(`${entry.module.padEnd(18)} not baked, left as is`); continue; }
    const json = readFileSync(join(dir, `${entry.module}.json`), 'utf8');
    const d = JSON.parse(json) as FaceData;
    const b = encodeFace(d, entry);
    if (JSON.stringify(decodeFace(b, entry)) !== JSON.stringify(d)) throw new Error(`${entry.module}: does not round-trip`);
    const src = moduleSource(b, entry, `${entry.module}.json`);
    writeFileSync(join(out, `${entry.module}.ts`), src);
    console.log(`${entry.module.padEnd(18)} ${(json.length / 1024).toFixed(0).padStart(5)} KiB JSON → ${(src.length / 1024).toFixed(0).padStart(4)} KiB, round-trips exactly`);
  }
}
