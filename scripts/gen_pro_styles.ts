// styles/pro-*.mplstyle -> src/core/data/prostyles.ts (the sheets verbatim). Run: node scripts/gen_pro_styles.ts
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const DIR = new URL('../styles/', import.meta.url);
const names = readdirSync(DIR).filter((f) => f.endsWith('.mplstyle')).toSorted();
const entries = names.map((f) => [f.replace(/\.mplstyle$/, ''), readFileSync(new URL(f, DIR), 'utf8')]);
writeFileSync(new URL('../src/core/data/prostyles.ts', import.meta.url),
  `// Generated by scripts/gen_pro_styles.ts from styles/*.mplstyle. Do not edit.\nexport const PRO_STYLES: ReadonlyMap<string, string> = new Map(${JSON.stringify(entries, null, 0)});\n`);
console.log(`wrote ${entries.length} styles`);
