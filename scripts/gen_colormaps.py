"""Generate src/colormaps/*.ts, src/core/data/colormaps.ts, fixtures/colormap_oracle.json."""
import base64, json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import Normalize, LogNorm, TwoSlopeNorm

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["viridis", "plasma", "inferno", "magma", "cividis", "twilight", "turbo",
         "coolwarm", "RdBu", "Greys", "Blues", "tab10", "tab20"]

def file_stem(name: str) -> str:
    return {"RdBu": "rdBu"}.get(name, name.lower())

def export_name(name: str) -> str:
    return {"RdBu": "rdBu"}.get(name, name.lower())

def pack(name: str) -> tuple[str, int, str]:
    c = plt.get_cmap(name)
    c._init()
    lut = c._lut[: c.N + 3].astype(np.float64).copy()
    lut[c.N + 2] = c(np.array([np.nan]))[0]
    trunc = np.clip(lut * 255, 0, 255).astype(np.uint8)
    rnd = np.clip(np.floor(lut * 255 + 0.5), 0, 255).astype(np.uint8)
    raw = trunc.tobytes() + rnd.tobytes()
    return name, int(c.N), base64.b64encode(raw).decode("ascii")

def e2e(name, norm, xs):
    return plt.get_cmap(name)(norm(np.asarray(xs, float)), bytes=True).tolist()

def norm_out(norm, xs):
    r = norm(np.asarray(xs, float))
    out = []
    for v in np.ma.filled(r, np.nan):
        if np.ma.is_masked(v) or (isinstance(v, float) and np.isnan(v)):
            out.append("nan")
        elif np.isposinf(v):
            out.append("inf")
        elif np.isneginf(v):
            out.append("-inf")
        else:
            out.append(float(v))
    return out

def main() -> None:
    os.makedirs(os.path.join(ROOT, "src/colormaps"), exist_ok=True)
    exports = []
    for n in NAMES:
        name, N, b64 = pack(n)
        stem, exp = file_stem(n), export_name(n)
        path = os.path.join(ROOT, "src/colormaps", f"{stem}.ts")
        with open(path, "w") as f:
            f.write(
                "// Generated by scripts/gen_colormaps.py from matplotlib 3.11.2. Do not edit.\n"
                "import type { CmapPack } from '../core/colormap.ts';\n"
                f"export const {exp}: CmapPack = {{ name: {json.dumps(name)}, N: {N}, b64: {json.dumps(b64)} }};\n"
            )
        exports.append((stem, exp))
        print(f"wrote {path}")
    with open(os.path.join(ROOT, "src/colormaps/all.ts"), "w") as f:
        for stem, exp in exports:
            f.write(f"import {{ {exp} }} from './{stem}.ts';\n")
        f.write("import type { CmapPack } from '../core/colormap.ts';\n")
        f.write(f"export const allColormaps: readonly CmapPack[] = [{', '.join(e for _, e in exports)}];\n")
        for _, exp in exports:
            f.write(f"export {{ {exp} }};\n")
    with open(os.path.join(ROOT, "src/core/data/colormaps.ts"), "w") as f:
        f.write(
            "// Generated by scripts/gen_colormaps.py. Name list only; packs live in src/colormaps/.\n"
            f"export const CMAP_NAMES: readonly string[] = {json.dumps(NAMES)};\n"
        )
    rng = np.random.default_rng(42)
    xs_rand = np.concatenate([rng.uniform(-0.5, 1.5, 500), [0, 1, 0.5, -1, 2, np.nan, np.inf, -np.inf]])
    def xs_json(a):
        return [("nan" if np.isnan(x) else "inf" if np.isposinf(x) else "-inf" if np.isneginf(x) else float(x)) for x in a]
    oracle = {
        "matplotlib": matplotlib.__version__,
        "e2e_viridis_norm": {"xs": [-1, 0, 0.5, 1, 2, "nan"],
                             "rgba": e2e("viridis", Normalize(0, 1), [-1, 0, 0.5, 1, 2, np.nan])},
        "e2e_plasma_log": {"xs": [0.1, 1, 10, 100, 1000, "nan"],
                           "rgba": e2e("plasma", LogNorm(vmin=1, vmax=1000), [0.1, 1, 10, 100, 1000, np.nan])},
        "e2e_coolwarm_twoslope": {"xs": [-3, -2, 0, 2, 4, 5, "nan"],
                                  "rgba": e2e("coolwarm", TwoSlopeNorm(vmin=-2, vcenter=0, vmax=4),
                                              [-3, -2, 0, 2, 4, 5, np.nan])},
        "fuzz_viridis": {"xs": xs_json(xs_rand), "rgba": plt.get_cmap("viridis")(xs_rand, bytes=True).tolist()},
        "listed_tab10": {"xs": [0, 0.05, 0.1, 0.5, 0.99, 1.0],
                         "rgba": plt.get_cmap("tab10")(np.array([0, 0.05, 0.1, 0.5, 0.99, 1.0]), bytes=True).tolist()},
        "reversed_viridis": {"xs": [0, 0.5, 1.0],
                             "rgba": plt.get_cmap("viridis_r")(np.array([0.0, 0.5, 1.0]), bytes=True).tolist()},
        "normalize": {"vmin": 0, "vmax": 10, "xs": [-1, 0, 5, 10, 11, "nan"],
                      "out": norm_out(Normalize(0, 10), [-1, 0, 5, 10, 11, np.nan])},
        "lognorm": {"vmin": 1, "vmax": 1000, "xs": [0.5, 1, 10, 1000, 2000, "nan"],
                    "out": norm_out(LogNorm(1, 1000), [0.5, 1, 10, 1000, 2000, np.nan])},
        "twoslope": {"vmin": -2, "vcenter": 0, "vmax": 4, "xs": [-3, -2, -1, 0, 2, 4, 5, "nan"],
                     "out": norm_out(TwoSlopeNorm(vmin=-2, vcenter=0, vmax=4), [-3, -2, -1, 0, 2, 4, 5, np.nan])},
    }
    with open(os.path.join(ROOT, "fixtures/colormap_oracle.json"), "w") as f:
        json.dump(oracle, f)
    print("wrote oracle")

if __name__ == "__main__":
    main()
